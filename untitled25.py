import random
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
import torchvision
import torchvision.transforms as transforms
import matplotlib.pyplot as plt
import seaborn as sns

from torch.utils.data import DataLoader
from sklearn.metrics import confusion_matrix, classification_report


# ---------------------------------------------------------
# 1. Configuration
# ---------------------------------------------------------
NAME = "C J ROHIT"
REGISTER_NUMBER = "212224243005"
BATCH_SIZE = 32
EPOCHS = 3
LEARNING_RATE = 0.001
DATA_DIR = "./data"
MODEL_PATH = "cnn_fashionmnist.pth"
RANDOM_SEED = 42

random.seed(RANDOM_SEED)
np.random.seed(RANDOM_SEED)
torch.manual_seed(RANDOM_SEED)

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Name:", NAME)
print("Register Number:", REGISTER_NUMBER)
print("Device:", device)


# ---------------------------------------------------------
# 2. Dataset and preprocessing
# ---------------------------------------------------------
transform = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize((0.5,), (0.5,))
])

train_dataset = torchvision.datasets.FashionMNIST(
    root=DATA_DIR,
    train=True,
    transform=transform,
    download=True
)

test_dataset = torchvision.datasets.FashionMNIST(
    root=DATA_DIR,
    train=False,
    transform=transform,
    download=True
)

train_loader = DataLoader(
    train_dataset, batch_size=BATCH_SIZE, shuffle=True
)

test_loader = DataLoader(
    test_dataset, batch_size=BATCH_SIZE, shuffle=False
)

class_names = train_dataset.classes

print("\nTraining images:", len(train_dataset))
print("Testing images:", len(test_dataset))
print("Image shape:", train_dataset[0][0].shape)


# ---------------------------------------------------------
# 3. CNN model
# ---------------------------------------------------------
class CNNClassifier(nn.Module):
    def __init__(self):
        super(CNNClassifier, self).__init__()

        self.conv1 = nn.Conv2d(
            in_channels=1, out_channels=32, kernel_size=3, padding=1
        )
        self.conv2 = nn.Conv2d(
            in_channels=32, out_channels=64, kernel_size=3, padding=1
        )
        self.conv3 = nn.Conv2d(
            in_channels=64, out_channels=128, kernel_size=3, padding=1
        )

        self.pool = nn.MaxPool2d(kernel_size=2, stride=2)

        # 28x28 -> 14x14 -> 7x7 -> 3x3 after pooling
        self.fc1 = nn.Linear(128 * 3 * 3, 128)
        self.fc2 = nn.Linear(128, 64)
        self.fc3 = nn.Linear(64, 10)

    def forward(self, x):
        x = self.pool(torch.relu(self.conv1(x)))
        x = self.pool(torch.relu(self.conv2(x)))
        x = self.pool(torch.relu(self.conv3(x)))

        x = x.view(x.size(0), -1)

        x = torch.relu(self.fc1(x))
        x = torch.relu(self.fc2(x))
        x = self.fc3(x)
        return x


model = CNNClassifier().to(device)
criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=LEARNING_RATE)

print("\nCNN model:")
print(model)


# ---------------------------------------------------------
# 4. Train the model
# ---------------------------------------------------------
def train_model(model, loader, epochs):
    epoch_losses = []

    for epoch in range(epochs):
        model.train()
        running_loss = 0.0

        for images, labels in loader:
            images = images.to(device)
            labels = labels.to(device)

            optimizer.zero_grad()
            outputs = model(images)
            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()

            running_loss += loss.item()

        average_loss = running_loss / len(loader)
        epoch_losses.append(average_loss)

        print(
            f"Epoch [{epoch + 1}/{epochs}], "
            f"Loss: {average_loss:.4f}"
        )

    return epoch_losses


print("\nTraining started...")
losses = train_model(model, train_loader, EPOCHS)

plt.figure(figsize=(8, 5))
plt.plot(range(1, EPOCHS + 1), losses, marker="o")
plt.xlabel("Epoch")
plt.ylabel("Training Loss")
plt.title("Training Loss per Epoch")
plt.xticks(range(1, EPOCHS + 1))
plt.grid(True)
plt.tight_layout()
plt.savefig("training_loss.png")
plt.show()


# ---------------------------------------------------------
# 5. Evaluate the model
# ---------------------------------------------------------
def test_model(model, loader):
    model.eval()
    correct = 0
    total = 0
    all_predictions = []
    all_labels = []

    with torch.no_grad():
        for images, labels in loader:
            images = images.to(device)
            labels = labels.to(device)

            outputs = model(images)
            predicted = torch.argmax(outputs, dim=1)

            total += labels.size(0)
            correct += (predicted == labels).sum().item()

            all_predictions.extend(predicted.cpu().numpy())
            all_labels.extend(labels.cpu().numpy())

    accuracy = 100.0 * correct / total
    print(f"\nTest Accuracy: {accuracy:.2f}%")

    cm = confusion_matrix(all_labels, all_predictions)
    plt.figure(figsize=(10, 8))
    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cmap="Blues",
        xticklabels=class_names,
        yticklabels=class_names
    )
    plt.xlabel("Predicted")
    plt.ylabel("Actual")
    plt.title("Confusion Matrix")
    plt.tight_layout()
    plt.savefig("confusion_matrix.png")
    plt.show()

    print("\nClassification Report:")
    print(classification_report(
        all_labels,
        all_predictions,
        target_names=class_names,
        zero_division=0
    ))

    return accuracy


accuracy = test_model(model, test_loader)


# ---------------------------------------------------------
# 6. Predict new/unseen test images
# ---------------------------------------------------------
def predict_image(model, image_index, dataset):
    model.eval()
    image, actual_label = dataset[image_index]

    with torch.no_grad():
        input_image = image.unsqueeze(0).to(device)
        output = model(input_image)
        predicted_label = torch.argmax(output, dim=1).item()

    plt.figure(figsize=(4, 4))
    plt.imshow(image.squeeze(), cmap="gray")
    plt.title(
        f"Actual: {class_names[actual_label]}\n"
        f"Predicted: {class_names[predicted_label]}"
    )
    plt.axis("off")
    plt.tight_layout()
    plt.savefig(f"prediction_{image_index}.png")
    plt.show()

    print(
        f"Actual: {class_names[actual_label]}, "
        f"Predicted: {class_names[predicted_label]}"
    )


predict_image(model, image_index=85, dataset=test_dataset)
predict_image(model, image_index=82, dataset=test_dataset)


